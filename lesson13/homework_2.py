# 2.	В конец существующего текстового файла записать три новые строки текста. Записываемые строки вводятся с клавиатуры.


# Открываем файл в режиме добавления (append)
with open("text.txt", "a", encoding="utf-8") as file:
    print("Введите 3 новые строки для добавления в конец существующего файла:")
    for i in range(3):
        line = input(f"Строка {i + 1}: ")
        file.write(line + "\n")

print("Строки добавлены в конец файла text.txt")
